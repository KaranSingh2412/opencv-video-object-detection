# --------------------------------------
# 3. Find Object Class Name
# --------------------------------------

def coco_class_name(class_id: int) -> str:

    """Map a model class id to its name; unknown ids get a diagnostic name."""

    return COCO_LABEL_MAP.get(int(class_id), f"unknown_id_{class_id}")
